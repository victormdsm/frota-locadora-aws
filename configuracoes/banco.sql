-- ---------- Tabelas ----------

CREATE TABLE IF NOT EXISTS marca (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS carro (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modelo        VARCHAR(255),
    placa         VARCHAR(255) UNIQUE,
    ano           INTEGER,
    valor_diaria  NUMERIC(10,2),
    status        VARCHAR(20) CHECK (status IN ('DISPONIVEL', 'LOCADO', 'MANUTENCAO')),
    marca_id      BIGINT REFERENCES marca (id)
);

CREATE TABLE IF NOT EXISTS usuario (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(255),
    username  VARCHAR(255) NOT NULL UNIQUE,
    senha     VARCHAR(255) NOT NULL,              -- hash BCrypt, nunca a senha pura
    role      VARCHAR(20)  NOT NULL CHECK (role IN ('ADMIN', 'USER'))
);

CREATE TABLE IF NOT EXISTS locacao (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carro_id           BIGINT REFERENCES carro (id),
    usuario_id         BIGINT REFERENCES usuario (id),
    data_inicio        DATE,
    data_fim_prevista  DATE,
    data_devolucao     DATE,
    valor_total        NUMERIC(10,2),
    status             VARCHAR(20) CHECK (status IN ('ATIVA', 'FINALIZADA', 'CANCELADA'))
);

